/**
 * Test helpers: record what an agent does during a test, in memory.
 *
 *   import OpenAI from 'openai'
 *   import { capture } from 'zizkadb-sdk'
 *
 *   it('answers refund questions with the policy search', async () => {
 *     const run = await capture({ clients: [OpenAI] }, () => myAgent('How long do refunds take?'))
 *     expect(run.toolCalls).toEqual(['search_policies'])
 *     expect(run.errors).toEqual([])
 *   })
 *
 * `capture()` records the OpenAI / Anthropic calls made inside the callback
 * with their causal links, in memory: nothing is sent to a ZizkaDB server, and
 * any `instrument()` the app set up stays quiet for the duration. The LLM calls
 * themselves still go to your provider (or to whatever mock your test uses).
 *
 * Tests generated by `npx zizkadb-sdk test from-session` are built on it.
 */

import { _instrument, _setCapturing, Recorder } from './instrument'

export const ERROR_EVENTS = new Set(['error', 'llm_error', 'tool_error', 'chain_error'])
export const TOOL_EVENTS = new Set(['tool_call', 'tool_start', 'mcp_tool_call'])

/** Tool name from an event payload, whichever SDK path wrote it. */
export function toolName(data: Record<string, unknown>): string | null {
  for (const key of ['tool', 'tool_name', 'name']) {
    const v = data?.[key]
    if (typeof v === 'string' && v) return v
  }
  return null
}

export interface CapturedEvent {
  eventId: string
  event: string
  data: Record<string, any>
  parentId: string | null
}

export class CapturedRun {
  readonly events: CapturedEvent[] = []

  /** Names of the tools the model called, in order. */
  get toolCalls(): string[] {
    return this.events
      .filter((e) => TOOL_EVENTS.has(e.event))
      .map((e) => toolName(e.data))
      .filter((n): n is string => n !== null)
  }

  get errors(): CapturedEvent[] {
    return this.events.filter((e) => ERROR_EVENTS.has(e.event))
  }

  /** Model output texts, in order. */
  get outputs(): string[] {
    return this.events.filter((e) => e.event === 'llm_end' && e.data.output).map((e) => e.data.output as string)
  }
}

export interface CaptureOptions {
  /** Client classes (`OpenAI`, `Anthropic`) or instances the agent uses. */
  clients: unknown[]
  agent?: string
}

/** Run `fn` and return everything its LLM calls did, recorded in memory. */
export async function capture(options: CaptureOptions, fn: () => unknown | Promise<unknown>): Promise<CapturedRun> {
  const run = new CapturedRun()
  let n = 0
  const memory = {
    async log(o: { event: string; data: Record<string, unknown>; parentId?: string }) {
      const eventId = `captured-${++n}`
      run.events.push({ eventId, event: o.event, data: o.data as Record<string, any>, parentId: o.parentId ?? null })
      return { eventId }
    },
  }
  const inst = _instrument(new Recorder(memory, options.agent ?? 'test-agent', true, true), options.clients)
  _setCapturing(true)
  try {
    await fn()
  } finally {
    await inst.flush()
    inst.uninstrument()
    _setCapturing(false)
  }
  return run
}
