"""Test helpers: record what an agent does during a test, in memory.

    from zizkadb.testing import capture

    def test_refund_question():
        with capture() as run:
            answer = my_agent("How long do refunds take?")
        assert run.tool_calls == ["search_policies"]
        assert not run.errors

``capture()`` uses :func:`zizkadb.instrument` with an in-memory recorder, so
OpenAI, Anthropic and LiteLLM calls made inside the block are recorded with
their causal links, and nothing is sent to a ZizkaDB server. The LLM calls
themselves still go to your provider (or to whatever mock your test uses).

Tests generated by ``zizkadb test from-session`` are built on this helper.
"""

from __future__ import annotations

import itertools
from contextlib import contextmanager
from dataclasses import dataclass, field
from typing import Any, Iterator

from . import instrumentation

ERROR_EVENTS = frozenset({"error", "llm_error", "tool_error", "chain_error"})
TOOL_EVENTS = frozenset({"tool_call", "tool_start", "mcp_tool_call"})


def tool_name(data: dict[str, Any]) -> str | None:
    """Tool name from an event payload, whichever SDK path wrote it."""
    for key in ("tool", "tool_name", "name"):
        value = data.get(key)
        if isinstance(value, str) and value:
            return value
    return None


@dataclass
class CapturedEvent:
    event_id: str
    event: str
    data: dict[str, Any]
    parent_id: str | None


@dataclass
class CapturedRun:
    """Everything recorded inside one ``capture()`` block, oldest first."""

    events: list[CapturedEvent] = field(default_factory=list)

    @property
    def tool_calls(self) -> list[str]:
        """Names of the tools the model called, in order."""
        return [n for e in self.events if e.event in TOOL_EVENTS for n in [tool_name(e.data)] if n]

    @property
    def errors(self) -> list[CapturedEvent]:
        return [e for e in self.events if e.event in ERROR_EVENTS]

    @property
    def outputs(self) -> list[str]:
        """Model output texts, in order."""
        return [e.data["output"] for e in self.events if e.event == "llm_end" and e.data.get("output")]


class _MemoryInstrumentation(instrumentation.Instrumentation):
    def __init__(self, run: CapturedRun, agent: str) -> None:
        super().__init__(db=None, agent=agent, capture_content=True)
        self._run = run
        self._ids = itertools.count(1)

    def _record(self, event: str, data: dict[str, Any], parent_id: str | None) -> str:
        event_id = f"captured-{next(self._ids)}"
        if parent_id is None and self._run.events and event != "user_message":
            parent_id = self._run.events[-1].event_id
        self._run.events.append(CapturedEvent(event_id, event, data, parent_id))
        return event_id

    def _write_sync(self, event: str, data: dict[str, Any], parent_id: str | None) -> str | None:
        return self._record(event, data, parent_id)

    async def _write_async(self, event: str, data: dict[str, Any], parent_id: str | None) -> str | None:
        return self._record(event, data, parent_id)


@contextmanager
def capture(
    agent: str = "test-agent",
    providers: tuple[str, ...] = ("openai", "anthropic", "litellm"),
) -> Iterator[CapturedRun]:
    """Record LLM and tool activity inside the block, without a server.

    If the code under test already called :func:`zizkadb.instrument`, that
    instrumentation is paused for the block and restored afterwards.
    """
    previous = instrumentation._active
    if previous is not None:
        previous.uninstrument()
    run = CapturedRun()
    inst = instrumentation._apply(_MemoryInstrumentation(run, agent), providers)
    try:
        yield run
    finally:
        inst.uninstrument()
        if previous is not None:
            instrumentation.instrument(
                previous._db,
                previous.agent,
                providers=previous.providers,
                capture_content=previous.capture_content,
            )


__all__ = ["capture", "CapturedRun", "CapturedEvent", "tool_name"]
