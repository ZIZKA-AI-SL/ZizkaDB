"""Turn a recorded session into a regression test (``zizkadb test from-session``).

Writes two files:

- ``<out>/zizkadb_sessions/<name>.json``: a snapshot of the session (user
  inputs, the tools the agent called, its final answer, any errors).
- ``<out>/test_<name>.py``: a pytest test that replays the user inputs
  through your agent inside :func:`zizkadb.testing.capture` and checks that
  it calls the same tools, in the same order, without errors.
"""

from __future__ import annotations

import json
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable

from .testing import ERROR_EVENTS, TOOL_EVENTS, tool_name

SNAPSHOT_DIR = "zizkadb_sessions"


def _text(data: dict[str, Any]) -> str | None:
    for key in ("text", "content", "message", "input", "query"):
        value = data.get(key)
        if isinstance(value, str) and value:
            return value
    return None


def build_snapshot(session_id: str, agent: str, events: Iterable[Any]) -> dict[str, Any]:
    """Summarise a session's events (oldest first) into what a test checks."""
    events = list(events)
    user_inputs, tools, errors = [], [], []
    final_output = None
    for e in events:
        data = e.data or {}
        if e.event == "user_message" and _text(data):
            user_inputs.append(_text(data))
        elif e.event in TOOL_EVENTS and tool_name(data):
            tools.append(tool_name(data))
        elif e.event in ERROR_EVENTS:
            errors.append({"event": e.event, "error": str(data.get("error") or data.get("message") or data)[:500]})
        if e.event in ("llm_end", "assistant_response", "agent_response") and isinstance(data.get("output") or _text(data), str):
            final_output = data.get("output") or _text(data)
    return {
        "session_id": session_id,
        "agent": agent,
        "recorded_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "user_inputs": user_inputs,
        "expected_tool_calls": tools,
        "recorded_final_output": final_output,
        "recorded_errors": errors,
        "event_count": len(events),
    }


def session_test_name(session_id: str) -> str:
    return "session_" + re.sub(r"[^0-9a-zA-Z]+", "_", session_id)[:12].strip("_").lower()


def render_test(snapshot: dict[str, Any], name: str, entry: str | None) -> str:
    """Source of the pytest file for a snapshot."""
    if entry:
        module, _, func = entry.partition(":")
        if not module or not func:
            raise ValueError("--entry must look like 'package.module:function'")
        agent_import = f"\nfrom {module} import {func} as _agent\n"
        runner = (
            "def run_agent(user_input: str):\n"
            "    \"\"\"Send one user message to the agent and return its answer.\"\"\"\n"
            "    return _agent(user_input)\n"
        )
    else:
        agent_import = ""
        runner = (
            "def run_agent(user_input: str):\n"
            "    \"\"\"Send one user message to your agent and return its answer.\n\n"
            "    Replace the body with a call into your agent, for example:\n"
            "        from my_app.agent import answer\n"
            "        return answer(user_input)\n"
            "    (or rerun the command with --entry my_app.agent:answer)\n"
            "    \"\"\"\n"
            "    pytest.skip(\"connect run_agent() to your agent, see the docstring\")\n"
        )
    if snapshot["recorded_errors"]:
        first = snapshot["recorded_errors"][0]["error"].replace('"""', "'''")[:200]
        note = (
            f"The recorded session ended with an error ({first!r}). This test\n"
            "# passes once the agent handles the same input without one. If the\n"
            "# recorded tool path was part of the bug, edit EXPECTED_TOOL_CALLS to\n"
            "# the path the agent should take."
        )
    else:
        note = (
            "If this session was a bad run, edit EXPECTED_TOOL_CALLS to the path\n"
            "# the agent should take; as recorded, the test locks in today's path."
        )
    return f'''"""Regression test generated by `zizkadb test from-session {snapshot["session_id"]}`.

Replays the user input recorded in that session ({snapshot["event_count"]} events,
agent {snapshot["agent"]!r}) through the agent and checks it takes the same
tool path without errors. Snapshot: {SNAPSHOT_DIR}/{name}.json
"""

import json
from pathlib import Path

import pytest

from zizkadb.testing import capture
{agent_import}
SNAPSHOT_FILE = Path(__file__).parent / "{SNAPSHOT_DIR}" / "{name}.json"
SNAPSHOT = json.loads(SNAPSHOT_FILE.read_text())

# {note}
EXPECTED_TOOL_CALLS = SNAPSHOT["expected_tool_calls"]


{runner}

def test_{name}():
    if not SNAPSHOT["user_inputs"]:
        pytest.skip("the recorded session has no user_message events to replay")
    with capture(agent=SNAPSHOT["agent"]) as run:
        for user_input in SNAPSHOT["user_inputs"]:
            run_agent(user_input)
    assert not run.errors, f"agent errors: {{[e.data for e in run.errors]}}"
    assert run.tool_calls == EXPECTED_TOOL_CALLS
'''


def write_files(snapshot: dict[str, Any], out_dir: Path, entry: str | None, force: bool = False) -> tuple[Path, Path]:
    """Write the snapshot and the test; refuse to overwrite unless ``force``."""
    name = session_test_name(snapshot["session_id"])
    snap_path = out_dir / SNAPSHOT_DIR / f"{name}.json"
    test_path = out_dir / f"test_{name}.py"
    for path in (snap_path, test_path):
        if path.exists() and not force:
            raise FileExistsError(f"{path} already exists (use --force to overwrite)")
    source = render_test(snapshot, name, entry)
    snap_path.parent.mkdir(parents=True, exist_ok=True)
    snap_path.write_text(json.dumps(snapshot, indent=2, ensure_ascii=False) + "\n")
    test_path.write_text(source)
    return snap_path, test_path
